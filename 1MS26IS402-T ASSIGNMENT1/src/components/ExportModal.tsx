import React, { useState } from 'react';
import { X, Copy, Check, Download, FileText, Printer, Code } from 'lucide-react';
import { PaperAnalysis } from '../types/research';

interface ExportModalProps {
  analysis: PaperAnalysis;
  onClose: () => void;
}

export const ExportModal: React.FC<ExportModalProps> = ({ analysis, onClose }) => {
  const [copied, setCopied] = useState(false);
  const [format, setFormat] = useState<'markdown' | 'json'>('markdown');

  const generateMarkdown = () => {
    return `# Research Analysis: ${analysis.paperTitle}
**Authors:** ${analysis.authors}  
**Year:** ${analysis.publicationYear} | **Domain:** ${analysis.domain}  
${analysis.sourceUrl ? `**URL:** ${analysis.sourceUrl}\n` : ''}

---

## 1. CORE CONCEPT EXTRACTION
*Word Count: ${analysis.coreConcept.wordCount || 150} words (< 300 words constraint)*

### Problem Statement
${analysis.coreConcept.problemStatement}

### Primary Methodology Introduced
${analysis.coreConcept.primaryMethodology}

### Key Mathematical / Algorithmic Breakthroughs
${analysis.coreConcept.keyBreakthroughs}

### Accessible Synthesis
${analysis.coreConcept.fullSummaryUnder300Words}

---

## 2. ARCHITECTURAL FLOWCHART (Mermaid.js)

${analysis.rawFlowchartText || `[FLOWCHART]\n${analysis.flowchart.mermaidCode}`}

### Components Breakdown
${analysis.flowchart.components.map((c) => `- **${c.name}** (${c.type}): ${c.description}`).join('\n')}

### Data Inputs
${analysis.flowchart.dataInputs.map((i) => `- ${i}`).join('\n')}

### Model Layers
${analysis.flowchart.modelLayers.map((l) => `- ${l}`).join('\n')}

### Data Outputs
${analysis.flowchart.dataOutputs.map((o) => `- ${o}`).join('\n')}

---

## 3. FUTURE WORK & INTERNSHIP OPPORTUNITIES (3rd-Year CS Level)

${analysis.studentOpportunities
  .map(
    (opp, i) => `### Opportunity ${i + 1}: ${opp.title}
- **Exact Extension:** ${opp.exactExtension}
- **Target Performance Metric:** ${opp.targetMetric}
- **Recommended Tech Stack:** ${opp.recommendedStack.join(', ')}
- **Difficulty / Timeline:** ${opp.difficulty} (~${opp.estimatedWeeks} weeks)
- **Starter Code / Repository:** ${opp.startingRepoOrLib}
- **Resume Bullet Point:**
  > "${opp.resumeBulletPoint}"
`
  )
  .join('\n\n')}

---
*Generated by CS Research Agent • Token Efficiency Safe*
`;
  };

  const content = format === 'markdown' ? generateMarkdown() : JSON.stringify(analysis, null, 2);

  const handleCopy = async () => {
    await navigator.clipboard.writeText(content);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const ext = format === 'markdown' ? 'md' : 'json';
    const mime = format === 'markdown' ? 'text/markdown' : 'application/json';
    const blob = new Blob([content], { type: `${mime};charset=utf-8` });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${analysis.paperTitle.toLowerCase().replace(/[^a-z0-9]+/g, '-')}-analysis.${ext}`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-md overflow-y-auto">
      <div className="bg-slate-900 border border-slate-700/80 rounded-2xl w-full max-w-3xl max-h-[88vh] flex flex-col shadow-2xl overflow-hidden animate-in fade-in zoom-in-95 duration-200">
        {/* Header */}
        <div className="bg-slate-900 px-6 py-4 border-b border-slate-800 flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div className="w-8 h-8 rounded-lg bg-indigo-500/20 text-indigo-400 flex items-center justify-center">
              <FileText className="w-4 h-4" />
            </div>
            <div>
              <h3 className="text-base font-bold text-white">Export Research Dossier</h3>
              <p className="text-xs text-slate-400">Download or copy report for Obsidian, Notion, or CV notes</p>
            </div>
          </div>
          <button onClick={onClose} className="p-1.5 text-slate-400 hover:text-white rounded-lg transition">
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Format Selector */}
        <div className="px-6 py-3 bg-slate-950/50 border-b border-slate-800 flex items-center justify-between">
          <div className="flex items-center gap-2">
            <button
              onClick={() => setFormat('markdown')}
              className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition ${
                format === 'markdown'
                  ? 'bg-indigo-600 text-white'
                  : 'bg-slate-800 text-slate-400 hover:text-slate-200'
              }`}
            >
              Markdown (.md)
            </button>
            <button
              onClick={() => setFormat('json')}
              className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition ${
                format === 'json'
                  ? 'bg-indigo-600 text-white'
                  : 'bg-slate-800 text-slate-400 hover:text-slate-200'
              }`}
            >
              JSON Data (.json)
            </button>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="flex items-center gap-1.5 px-3 py-1.5 bg-slate-800 hover:bg-slate-700 text-slate-200 border border-slate-700 rounded-lg text-xs transition"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied' : 'Copy Content'}</span>
            </button>
            <button
              onClick={handleDownload}
              className="flex items-center gap-1.5 px-3 py-1.5 bg-indigo-600 hover:bg-indigo-500 text-white rounded-lg text-xs font-semibold transition shadow"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download File</span>
            </button>
          </div>
        </div>

        {/* Content Box */}
        <div className="p-6 overflow-y-auto flex-1 bg-slate-950">
          <pre className="text-xs font-mono text-slate-300 whitespace-pre-wrap leading-relaxed bg-slate-900/60 p-4 rounded-xl border border-slate-800 max-h-[460px]">
            {content}
          </pre>
        </div>

        {/* Footer */}
        <div className="bg-slate-950 px-6 py-3 border-t border-slate-800 flex justify-end">
          <button
            onClick={onClose}
            className="px-4 py-1.5 bg-slate-800 hover:bg-slate-700 text-white text-xs rounded-lg transition"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
};
